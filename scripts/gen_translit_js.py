"""Copy the transliteration tables from src/translit.py into the JavaScript engine (site/engine.js and web/engine.js) so both stay identical.
   python scripts/gen_translit_js.py"""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]; sys.path.insert(0, str(ROOT / "src"))
import translit as T

J = lambda o: json.dumps(o, ensure_ascii=False)
block = f'''  /*TRANSLIT-START (generated by scripts/gen_translit_js.py from src/translit.py - do not edit by hand)*/
  const TL = {{ CONS: {J(T.CONS)}, NUKTA: {J(T.NUKTA)}, VOWEL: {J(T.VOWEL)}, MATRA: {J(T.MATRA)}, DIGITS: {J(T.DIGITS)}, LABIAL: {J(sorted(T.LABIAL))},
    DICT: {J(T.DICT)} }};
  /*TRANSLIT-END*/'''
for p in ("site/engine.js", "web/engine.js"):
    f = ROOT / p; s = f.read_text()
    a, b = s.find("  /*TRANSLIT-START"), s.find("/*TRANSLIT-END*/")
    s = s[:a] + block + s[b + len("/*TRANSLIT-END*/"):] if a >= 0 else s.replace("  // ---------------------------------------------------------------- models\n", block + "\n\n  // ---------------------------------------------------------------- models\n", 1)
    f.write_text(s)
print("ok")
